export function sampleShots(ipId: string): Shot[] {
  const sample = assistantSamples[ipId];
  if (!sample) throw new Error('这个 IP 仅提供资料预览，没有创作示例。');
  return sample.scenes.map(([title, description, dialogue, camera, assetIds, tone, continuity], i) => ({ id: `shot-${i + 1}`, title, description, dialogue, camera, assetIds: [...assetIds], duration: [8, 10, 6, 12, 14, 10][i], frame: i, clipStatus: 'idle', selected: false, failOnce: false, framing: camera === '手部特写' ? '特写' : i === 5 ? '远景' : '中景', action: description, tone, sound: ipId === 'sea' ? '海浪、木船轻响；对白时减弱环境声。' : ipId === 'lantern' ? '雪地脚步、纸张轻响；对白时减弱环境声。' : '山风、衣料与脚步声；对白时减弱环境声。', continuity }));
}
